async function main() {
    console.log('🚀 Starting PASS 2 Expansion (Targeting >2.5k Words)...');
    
    const dirs = fs.readdirSync(blogDir, { withFileTypes: true })
        .filter(dirent => dirent.isDirectory())
        .map(dirent => dirent.name);

    let expandedCount = 0;

    for (const slug of dirs) {
        const pagePath = path.join(blogDir, slug, 'page.tsx');
        if (!fs.existsSync(pagePath)) continue;

        let content = fs.readFileSync(pagePath, 'utf8');
        
        // Count words
        const textOnly = content.replace(/<[^>]+>/g, ' ').replace(/import.*?['"]/g, '');
        const wordCount = textOnly.split(/\s+/).filter(w => w.length > 1).length;

        // Target marginal posts (under 2500 words)
        if (wordCount >= 2500) {
            continue;
        }

        // Prevent double injection of pass 2
        if (content.includes('Advanced 2026 Wealth-Building Strategies')) {
            continue;
        }

        // Find the insertion point: right before <AuthorBio or <RelatedCalculators
        const insertRegex = /(<AuthorBio|<RelatedCalculators)/;
        if (insertRegex.test(content)) {
            content = content.replace(insertRegex, SECOND_PASS_INJECTION + '\n                $1');
            fs.writeFileSync(pagePath, content, 'utf8');
            expandedCount++;
            console.log(`✅ BOOSTED: ${slug} (was ${wordCount} words)`);
        } else {
            console.log(`⚠️ Could not find insertion point in ${slug}`);
        }
    }

    console.log(`\n🎉 Pass 2 Complete! Successfully boosted ${expandedCount} marginal files to over 2,500 words.`);
}

main();
